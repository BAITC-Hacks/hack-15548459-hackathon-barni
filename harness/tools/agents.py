"""Распределение задач между моделями: под-агенты и быстрые вызовы других моделей."""
from ..router import ROUTER
from . import tool


@tool
def delegate(task: str, role: str = "fast") -> str:
    """Поручает самостоятельную подзадачу отдельному под-агенту (со своими инструментами) и возвращает его итог.
    Полезно для параллельных исследований и больших объёмов работы. Под-агент НЕ видит текущий диалог —
    передай в task весь нужный контекст и чёткий формат результата.

    Args:
        task: Полная постановка подзадачи с контекстом и ожидаемым форматом ответа.
        role: Какая модель: "fast" (дешевле/быстрее) или "smart" (умнее).
    """
    from ..agent import Agent
    sub = Agent(role=role, exclude=["delegate"], persist=False, max_steps=12)
    return sub.run(task)


@tool
def ask_model(prompt: str, role: str = "fast") -> str:
    """Один запрос к другой модели без инструментов: классификация, перевод, суммаризация, генерация текста.
    Дешевле, чем делать это самому на большой модели.

    Args:
        prompt: Полный запрос с данными.
        role: "fast", "smart" или конкретная модель "провайдер:модель".
    """
    return ROUTER.ask(prompt, role=role)
