"""RAG по документам и долгосрочная память."""
from ..memory import MEMORY
from ..rag import INDEX
from . import tool


@tool
def search_docs(query: str, k: int = 5) -> list:
    """Ищет по смыслу во всех документах рабочей папки (pdf, docx, txt, md, csv, xlsx…) и возвращает
    самые подходящие фрагменты с именем файла. Используй для вопросов по документам кейса,
    а не читай все файлы целиком. Ссылайся на файл в ответе.

    Args:
        query: Что ищем, своими словами.
        k: Сколько фрагментов вернуть.
    """
    return INDEX.search(query, k)


@tool
def index_docs(force: bool = False) -> str:
    """Переиндексирует документы рабочей папки (после появления новых файлов). Обычно происходит само.

    Args:
        force: Пересобрать индекс полностью.
    """
    return INDEX.build(force=force)


@tool
def remember(fact: str, tags: str = "") -> str:
    """Сохраняет важный факт в долгосрочную память (переживает перезапуск и новые диалоги):
    предпочтения пользователя, найденные ключевые данные, принятые решения.

    Args:
        fact: Факт одной-двумя фразами, самодостаточный (понятный без контекста).
        tags: Теги через запятую.
    """
    return f"Запомнено (id={MEMORY.add(fact, tags)})"


@tool
def recall(query: str, k: int = 5) -> list:
    """Ищет в долгосрочной памяти факты, сохранённые раньше. Используй в начале задачи, если
    пользователь ссылается на прошлое («как в прошлый раз», «мои предпочтения»).

    Args:
        query: Что вспомнить.
        k: Сколько фактов вернуть.
    """
    return MEMORY.search(query, k)
